public class Rectangle {
    private double width = 1.0;
    private double height = 1.0;

    public Rectangle() {
        width = this.width;
        height = this.height;
    }

    public Rectangle(double width, double height){ 
        width = this.width;
        height = this.height;
    }

    public double getHeight(){ 
        return this.height;
    }

    public double getWidth(){ 
        return this.width;
    }

    
}
